def caption_code_blocks(text, num):
    """给非 mermaid 代码块加「代码 X-Y-Z」编号。

    2026-11-10 文档级审查 G-01 修复：旧实现把 mermaid 的**闭合围栏**
    （``` 且语言为空）误判为「无语言代码块的开围栏」，从而在图块内部
    插入一行 `**代码 X-1-1** · 示例（文本）`，破坏 mermaid 图且让
    check_structure 靠伪编号判 GREEN。现改为显式维护 in_fence 状态：
    只有处于围栏外时遇到的围栏才是开围栏，闭合围栏原样复制。
    """
    lines = text.splitlines()
    out, i, sec, seq = [], 0, 1, 0
    fence = re.compile(r'^```([A-Za-z0-9]*)\s*$')
    sec_re = re.compile(rf'^## {num}\.(\d+)')
    in_fence = False
    while i < len(lines):
        line = lines[i]
        if in_fence:
            out.append(line); i += 1
            if fence.match(line):
                in_fence = False
            continue
        msec = sec_re.match(line)
        if msec:
            sec = int(msec.group(1)); seq = 0
        mf = fence.match(line)
        if mf:
            lang = mf.group(1) or 'plain'
            if lang != 'mermaid':
                prev = out[-1].strip() if out else ''
                if not prev.startswith('**代码 '):
                    seq += 1
                    label = CODES.get(lang, '示例（文本）')
                    out.append(f'**代码 {num}-{sec}-{seq}** · {label}')
                    out.append('')
            out.append(line); i += 1
            in_fence = True
            continue
        out.append(line); i += 1
    return '\n'.join(out)

def convert_details(text):
    hints = []
    def repl(m):
        summary = re.search(r'<summary>(.*?)</summary>', m.group(0))
        title = summary.group(1).strip() if summary else '提示'
        body = re.sub(r'^<details[^>]*>.*?</summary>\s*', '', m.group(0), flags=re.S)
        body = re.sub(r'</details>\s*$', '', body).strip()
        prior = re.findall(r'^#### (例 [^\n]+)', text[:m.start()], re.M)
        hints.append((prior[-1] if prior else '', title, body))
        return ''
    text = re.sub(r'<details.*?</details>', repl, text, flags=re.S)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text, hints

